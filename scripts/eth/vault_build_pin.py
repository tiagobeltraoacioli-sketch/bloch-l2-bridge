#!/usr/bin/env python3
"""The build pin of contracts/eth/NativeEtherSourceVault.sol: deployments/ethereum-eth/vault-build.pin.json.

  python3 scripts/eth/vault_build_pin.py write [OUT_DIR]     after `forge build`: record the artifact's hashes
  python3 scripts/eth/vault_build_pin.py check [OUT_DIR]     exit 1 if the sources or the artifact differ from the pin

The pin states the sha256 of the two source files the vault is made of (its own, and the Ethereum vault it imports
the verifier interfaces from), the compiler settings of foundry.toml that decide the bytes, and the keccak256 of the
creation code and of the runtime code as forge builds them (immutables still zero in the runtime template). The
rehearsal compares the creation code it deploys with this pin; an auditor rebuilds and runs `check`. OUT_DIR defaults
to ./out. Standard library only (keccak from tools/signatario-stable/bridge_feed.py).
"""
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
PIN = ROOT / 'deployments/ethereum-eth/vault-build.pin.json'
SOURCES = ('contracts/eth/NativeEtherSourceVault.sol', 'contracts/usdt/ProvenanceSourceVault.sol')
ARTIFACT = 'NativeEtherSourceVault.sol/NativeEtherSourceVault.json'
sys.path.insert(0, str(ROOT / 'tools/signatario-stable'))
from bridge_feed import keccak256  # noqa: E402


def settings():
    text = (ROOT / 'foundry.toml').read_text()
    get = lambda key: re.search(rf'^{key}\s*=\s*"?([^"\n]+)"?\s*$', text, re.M).group(1).strip()  # noqa: E731
    return {'solc': get('solc_version'), 'evmVersion': get('evm_version'), 'optimizer': get('optimizer') == 'true',
            'optimizerRuns': int(get('optimizer_runs')), 'bytecodeHash': get('bytecode_hash')}


def build(out_dir):
    art = json.loads((Path(out_dir) / ARTIFACT).read_text())
    creation = bytes.fromhex(art['bytecode']['object'][2:])
    runtime = bytes.fromhex(art['deployedBytecode']['object'][2:])
    return {
        'domain': 'bloch.bridge.native-ether-vault-build.v1',
        'notes': 'GENERATED by scripts/eth/vault_build_pin.py from a forge build of this tree; never edit by hand. The vault of the '
                 'ethereum-eth route (bETH). UNAUDITED; nothing is deployed. The runtime hash is of the build template: a deployed '
                 'vault has its immutables written in, so its code hash differs per deployment (vault_pontes.py verify prints it).',
        'contract': 'contracts/eth/NativeEtherSourceVault.sol:NativeEtherSourceVault',
        'compiler': settings(),
        'source': {p: hashlib.sha256((ROOT / p).read_bytes()).hexdigest() for p in SOURCES},
        'forge': {'creationCodeBytes': len(creation), 'creationCodeKeccak': '0x' + keccak256(creation).hex(),
                  'runtimeTemplateBytes': len(runtime), 'runtimeTemplateKeccak': '0x' + keccak256(runtime).hex()},
        'diff': {'against': 'contracts/usdt/ProvenanceSourceVault.sol', 'pinnedBy': 'scripts/eth/vault_diff.py'},
    }


def main(argv):
    mode = argv[0] if argv else ''
    if mode not in ('write', 'check'):
        raise SystemExit(__doc__)
    doc = build(argv[1] if len(argv) > 1 else ROOT / 'out')
    text = json.dumps(doc, indent=2) + '\n'
    if mode == 'write':
        PIN.write_text(text)
        print(f'wrote {PIN.relative_to(ROOT)}: creation {doc["forge"]["creationCodeKeccak"]} ({doc["forge"]["creationCodeBytes"]} bytes)')
        return 0
    if not PIN.exists() or PIN.read_text() != text:
        print(f'{PIN.relative_to(ROOT)} differs from this build and these sources: {doc["forge"]["creationCodeKeccak"]}')
        return 1
    print(f'{PIN.relative_to(ROOT)} matches: creation {doc["forge"]["creationCodeKeccak"]}, runtime template '
          f'{doc["forge"]["runtimeTemplateKeccak"]} ({doc["forge"]["runtimeTemplateBytes"]} bytes; EIP-170 limit 24,576)')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
